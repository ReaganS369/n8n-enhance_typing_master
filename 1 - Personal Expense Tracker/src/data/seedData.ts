// Helper to format ISO date string 'YYYY-MM-DD'
const getDateStr = (offsetDays: number = 0, targetMonthOffset: number = 0): string => {
  const d = new Date();
  if (targetMonthOffset !== 0) {
    d.setMonth(d.getMonth() + targetMonthOffset);
  }
  d.setDate(d.getDate() - offsetDays);
  return d.toISOString().split('T')[0];
};

